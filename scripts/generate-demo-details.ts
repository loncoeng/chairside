// Writes seed/demo-customer-details.sql: an address and a birthday for most
// of the sample guests.
//
// Kept apart from generate-demo-bookings.ts on purpose. That script draws
// every booking from one fixed random sequence, and drawing anything extra
// from it would move three months of bookings to add a column.
//
// **Every street and building here is made up.** 示範街, Rua da Amostra,
// 樣板花園 — names chosen to read as a sample at a glance, so that nobody
// mistakes one for a real address or goes looking for it.
//
// UPDATEs rather than INSERTs, and only where the field is still empty. The
// public instance applies this on every deploy; a detail somebody corrected
// through the screen stays corrected.
//
// Run it with `npm run demo:details`. The output is committed.

import { writeFileSync } from "node:fs";

/** The twelve in demo.sql, and the generated guests after them. */
const IDS = [
  ...Array.from({ length: 12 }, (_, i) => i + 1),
  ...Array.from({ length: 240 }, (_, i) => i + 101),
];

let seed = 20260927;
function random(): number {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
}
const pick = <T,>(list: readonly T[]): T => list[Math.floor(random() * list.length)]!;
const between = (lo: number, hi: number) => lo + Math.floor(random() * (hi - lo + 1));

const ZH_STREETS = ["示範街", "樣本大馬路", "虛構巷", "範例圍", "假名斜巷", "測試前地"];
const ZH_BUILDINGS = ["樣板花園", "示範大廈", "範例中心", "虛構閣", "樣本新邨"];
const PT_STREETS = ["Rua da Amostra", "Travessa do Exemplo", "Avenida Fictícia", "Estrada do Modelo"];
const PT_BUILDINGS = ["Edf. Modelo", "Edf. Exemplo", "Jardim Fictício"];
const FLATS = ["A", "B", "C", "D", "E", "F"];

/**
 * Mostly Macau, some Hong Kong and the mainland — the same spread as the
 * dialling codes on the phone numbers.
 */
function address(): string {
  const roll = random();
  const no = between(1, 188);
  const floor = between(1, 32);
  const flat = pick(FLATS);
  if (roll < 0.55) return `澳門${pick(ZH_STREETS)}${no}號${pick(ZH_BUILDINGS)}${floor}樓${flat}座`;
  if (roll < 0.75) return `${pick(PT_STREETS)} n.º ${no}, ${pick(PT_BUILDINGS)} ${floor}.º ${flat}, Macau`;
  if (roll < 0.9) return `香港九龍${pick(ZH_STREETS)}${no}號${pick(ZH_BUILDINGS)}${floor}樓${flat}室`;
  return `廣東省珠海市${pick(ZH_STREETS)}${no}號${pick(ZH_BUILDINGS)}${floor}${String(between(1, 8)).padStart(2, "0")}室`;
}

function birthday(): string {
  const year = between(1960, 2008);
  const month = between(1, 12);
  const day = between(1, 28);
  return `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

const quote = (s: string | null) => (s === null ? "NULL" : `'${s.replaceAll("'", "''")}'`);

const lines: string[] = [];
for (const id of IDS) {
  // Not everybody gives either. A sample where every field is filled looks
  // like a form, not like a salon's records.
  const a = random() < 0.75 ? address() : null;
  const b = random() < 0.65 ? birthday() : null;
  if (a === null && b === null) continue;
  lines.push(
    `UPDATE customers SET address = COALESCE(address, ${quote(a)}), birthday = COALESCE(birthday, ${quote(b)})` +
      ` WHERE id = ${id} AND (address IS NULL OR birthday IS NULL);`,
  );
}

const sql = `-- Generated by scripts/generate-demo-details.ts. Do not edit by hand.
--
-- Addresses and birthdays for the sample guests. Every street and building
-- is invented. Fills only what is empty, so it is safe to apply on every
-- deploy and never overwrites a correction made through the screen.

${lines.join("\n")}
`;

writeFileSync(new URL("../seed/demo-customer-details.sql", import.meta.url), sql);
console.log(`seed/demo-customer-details.sql: ${lines.length} guests`);
