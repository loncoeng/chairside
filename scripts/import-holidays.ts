// Writes seed/holidays.sql from Google's public holiday calendars.
// Run by hand about once a year. The output is committed so deploys and the
// browser demo don't depend on the feed.
//
// A feed instead of a library: date-holidays and Nager.Date have no Macau, and
// Nager.Date returns about 6 China holidays out of roughly 15.
//
//   node scripts/import-holidays.ts

import { writeFileSync } from "node:fs";

/**
 * Macau, Hong Kong and mainland China. Macau's id is `en.mo`; `en.macau` and
 * `en.macao` return 500. Google publishes no list of ids.
 */
const FEEDS: { region: "MO" | "HK" | "CN"; id: string }[] = [
  { region: "MO", id: "en.mo" },
  { region: "HK", id: "en.hong_kong" },
  { region: "CN", id: "en.china" },
];

const url = (id: string) =>
  `https://calendar.google.com/calendar/ical/${id}%23holiday%40group.v.calendar.google.com/public/basic.ics`;

type Holiday = { region: string; date: string; name: string };

/** Minimal iCal parse: date-valued DTSTART and SUMMARY only (no times, recurrence or zones). */
function parse(region: string, ics: string): Holiday[] {
  const out: Holiday[] = [];

  for (const [block] of ics.matchAll(/BEGIN:VEVENT[\s\S]*?END:VEVENT/g)) {
    const date = /DTSTART;VALUE=DATE:(\d{4})(\d{2})(\d{2})/.exec(block);
    const summary = /SUMMARY:(.*)/.exec(block);
    if (!date || !summary) continue;

    out.push({
      region,
      date: `${date[1]}-${date[2]}-${date[3]}`,
      // iCal escapes commas and semicolons. Unfolding continuation lines is
      // not needed: these names are short.
      name: summary[1]!.trim().replace(/\\,/g, ",").replace(/\\;/g, ";"),
    });
  }

  return out;
}

const quote = (value: string) => `'${value.replace(/'/g, "''")}'`;
const today = new Date(Date.now() + 8 * 60 * 60 * 1000).toISOString().slice(0, 10);

const rows: string[] = [];
let id = 1;

for (const feed of FEEDS) {
  const response = await fetch(url(feed.id));
  if (!response.ok) {
    throw new Error(`${feed.region}: HTTP ${response.status} from ${feed.id}`);
  }

  const found = parse(feed.region, await response.text());

  // The unique index allows one row per region and date, so names on the same day are
  // merged (e.g. "New Year's Eve" and "New Year's Eve Afternoon").
  const merged = new Map<string, string[]>();
  for (const holiday of found) {
    const names = merged.get(holiday.date) ?? [];
    if (!names.includes(holiday.name)) names.push(holiday.name);
    merged.set(holiday.date, names);
  }

  for (const [date, names] of [...merged.entries()].sort()) {
    rows.push(
      `  (${id++}, ${quote(feed.region)}, ${quote(date)}, ${quote(names.join(" / "))}, ` +
        `${quote(`Google Calendar (${feed.id})`)}, ${quote(today)})`,
    );
  }

  console.log(`${feed.region}: ${merged.size} days from ${found.length} entries`);
}

const br = String.fromCharCode(10);
const years = rows
  .map((r) => /'(\d{4})-/.exec(r)?.[1])
  .filter((y): y is string => y !== undefined)
  .sort();

const sql = `-- Generated by scripts/import-holidays.ts on ${today}. Do not edit by hand.
--
-- Public holidays for Macau, Hong Kong and the mainland, ${years[0]} to
-- ${years[years.length - 1]}, from Google's public calendars. ${rows.length} days.
--
-- Committed rather than fetched at deploy time, so that the shop's instance
-- does not depend on anybody's feed being up, and the browser demo gets the
-- same dates without asking anybody for them.
--
-- \`source\` and \`fetched_on\` are on every row. Entering a year with nothing
-- on file should put a notice on the screen, not an empty calendar, and that
-- is only answerable if each row says where it came from and when.

DELETE FROM holidays;

INSERT INTO holidays (id, region, date, name, source, fetched_on) VALUES
${rows.join(`,${br}`)};
`;

writeFileSync(new URL("../seed/holidays.sql", import.meta.url), sql);
console.log(`seed/holidays.sql: ${rows.length} days, ${years[0]} to ${years[years.length - 1]}`);
