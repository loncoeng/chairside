// Writes seed/logins.sql: the demo's accounts, with hashed passwords.
//
// The passwords are in this file and printed on the demo's sign-in screen.
// That is correct rather than careless: the database they open is invented,
// and in the demo it lives in the visitor's own browser. Hiding them would
// only mean nobody could get in.
//
// **A shop running this for real does not apply this file.** It sets its own,
// which is why the seed leaves login_id and password_hash NULL for everybody
// and this is a separate step.
//
//   node scripts/make-logins.ts

import { writeFileSync } from "node:fs";

import { hashPassword } from "../src/db/session.ts";

/** Who can sign in, and as what. Three roles, so all three can be tried. */
const ACCOUNTS: { id: number; loginId: string; password: string; who: string }[] = [
  { id: 1, loginId: "aoi", password: "chairside-demo", who: "Aoi — owner" },
  { id: 2, loginId: "ren", password: "chairside-demo", who: "Ren — stylist" },
  { id: 8, loginId: "hana", password: "chairside-demo", who: "Hana — assistant" },
];

const rows: string[] = [];

for (const account of ACCOUNTS) {
  const hash = await hashPassword(account.password);
  rows.push(
    `UPDATE staff SET login_id = '${account.loginId}', password_hash = '${hash}' WHERE id = ${account.id};`,
  );
}

const sql = `-- Generated by scripts/make-logins.ts. Do not edit by hand.
--
-- Sign-ins for the public demo. The passwords are all the same and printed on
-- the demo's own screen: the database they open is invented, and in the demo
-- it lives in the visitor's browser.
--
-- ${ACCOUNTS.map((a) => `${a.loginId} (${a.who})`).join(", ")}
--
-- **A shop running this does not apply this file.** Everybody else keeps
-- login_id and password_hash NULL, and somebody with no password set cannot
-- sign in — that is checked, rather than left to read as an empty one.

${rows.join("\n")}
`;

writeFileSync(new URL("../seed/logins.sql", import.meta.url), sql);
console.log(`seed/logins.sql: ${ACCOUNTS.length} accounts`);
